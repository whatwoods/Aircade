/**
 * 造字记 · Hanzi Merge — 字库与配方表（唯一数据源，供审查）
 *
 * 规则：
 *  - 每条配方都是真实的汉字构形拆分（会意 / 形声 / 指事），不编造。
 *  - src = '说文'：依据《说文解字》（大徐本），check 是从说文原文（转简体）中摘出的片段，
 *    tools/verify-data.ts 会逐条到说文数据里核对。
 *  - trad = 真实的繁体字形（与 OpenCC 简→繁一致，界面显示「繁体」）；sw = 说文字头与今字不同时的
 *    篆文隶定字头（只供校验查找，不在界面上显示——它不是繁体，且多半不在字体子集里）。
 *  - src = '今'：简化字、后起字或现代通行的构形分析（说文未收或结构已变），basis 里写明理由。
 *  - 部件顺序 = 位置顺序：⿰ 左→右；⿱ 上→下；包围结构（⿴⿵⿸⿹⿺）外→内；
 *    三部件 '品' = 一上两下（⿱A⿰BC）。
 *  - ph = 形声字中声旁在 parts 里的下标；phn = 声旁的本字（今字形是它的简省/讹变时填，如 思 上部本作囟），
 *    卡片标签写作「田（本作囟）表音」，校验脚本要求 basis 与之一致。
 *  - tier = 首次出现的章节（1 叠字 … 6 三部件），供关卡生成与难度曲线使用。
 *  - 偏旁变体（水→氵 等）不单独成为部件：部件牌上写本字，入字后显示 vv（逐字给定，与 parts 一一对应的
 *    实际字形；不能按位置推断——炎/灭/灾/焚 下部仍是火，只有 照/焦 才是灬）。BASES.v 只列出某个部件
 *    可能出现的变体，校验脚本要求 vv 中每个字要么是部件本字、要么是它在 BASES.v 中的一个变体，
 *    并在提供 IDS 数据时逐字对照真实字形结构。凡部件带有 BASES.v 的配方都必须写 vv。
 */

export type Struct = '⿰' | '⿱' | '⿴' | '⿵' | '⿸' | '⿹' | '⿺' | '品';
export type Method = '会意' | '形声' | '指事';
export type Src = '说文' | '今';

export interface BaseDef {
  c: string;
  py: string;
  /** 释义 / 名称 */
  g: string;
  /** 此部件可能出现的偏旁变体（l 左 / r 右 / t 上 / b 下）。只是允许值清单，实际用哪个由配方的 vv 决定；
   *  值为 '' 表示字体无独立字形（竹字头、羊字头），入字时按比例压扁本字 */
  v?: Partial<Record<'l' | 'r' | 't' | 'b', string>>;
  /** 变体的名称（图鉴与提示用），如「三点水」 */
  vn?: string;
}

export interface RecipeDef {
  c: string;
  py: string;
  parts: string[];
  s: Struct;
  t: Method;
  tier: number;
  g: string;
  src: Src;
  /** 说文原文片段（简体），src='说文' 时必填，校验脚本据此核对 */
  check?: string;
  /** 卡片上显示的构形依据 */
  basis: string;
  /** 入字后各部件的实际显示字形（与 parts 等长，逐字对应）；部件带 BASES.v 时必填 */
  vv?: string;
  /** 真实繁体字形（界面显示「繁体」） */
  trad?: string;
  /** 说文字头（与今字不同时），仅供校验 */
  sw?: string;
  ph?: number;
  /** 声旁本字（今形为其简省/讹变时） */
  phn?: string;
}

